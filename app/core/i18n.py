def t(key: str, lang: str = "fa", **kwargs: Any) -> str:
    """Translate a key for the given language."""
    catalog = TRANSLATIONS.get(lang) or TRANSLATIONS["fa"]
    text = catalog.get(key) or TRANSLATIONS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def get_all(lang: str = "fa") -> dict[str, str]:
    return TRANSLATIONS.get(lang, TRANSLATIONS["fa"]).copy()
